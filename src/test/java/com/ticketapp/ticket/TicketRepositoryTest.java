
package com.ticketapp.ticket;

import com.ticketapp.db.Database;
import com.ticketapp.model.Ticket;

import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.Arrays;

import static org.junit.jupiter.api.Assertions.*;

class TicketRepositoryTest {

    private static final String URL =
        "jdbc:h2:mem:ticket_security_test;DB_CLOSE_DELAY=-1";

    private Database testDatabase() {
        return new Database(null) {
            @Override
            public Connection connect() throws java.sql.SQLException {
                return DriverManager.getConnection(URL);
            }
        };
    }

    private FieldEncryptor testEncryptor() {
        byte[] key = new byte[32];
        Arrays.fill(key, (byte) 7);
        return new FieldEncryptor(key);
    }

    @Test
    void sqlInjectionIsStoredAsDataAndContactIsEncrypted() throws Exception {
        Database db = testDatabase();

        try (Connection conn = db.connect();
             Statement stmt = conn.createStatement()) {

            stmt.execute("DROP TABLE IF EXISTS tickets");

            stmt.execute("""
                CREATE TABLE tickets (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    owner_id BIGINT NOT NULL,
                    assignee_id BIGINT,
                    title VARCHAR(200),
                    description VARCHAR(4000),
                    contact_enc VARCHAR(2000),
                    status VARCHAR(30),
                    created_at TIMESTAMP,
                    version BIGINT
                )
                """);
        }

        TicketRepository repo =
            new TicketRepository(db, testEncryptor());

        Ticket ticket = new Ticket();
        ticket.setOwnerId(1L);
        ticket.setTitle("'; DROP TABLE tickets; --");
        ticket.setDescription("SQL injection test");
        ticket.setContactInfo("private@example.com");
        ticket.setStatus(Ticket.Status.OPEN);

        Ticket saved = repo.insert(ticket);

        assertTrue(saved.getId() > 0);

        Ticket retrieved = repo.findById(saved.getId()).orElseThrow();

        assertEquals("'; DROP TABLE tickets; --", retrieved.getTitle());
        assertEquals("private@example.com", retrieved.getContactInfo());
        assertEquals(1, repo.countOpenByOwner(1L));

        try (Connection conn = db.connect();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(
                 "SELECT contact_enc FROM tickets WHERE id = " + saved.getId())) {

            assertTrue(rs.next());

            String stored = rs.getString("contact_enc");

            assertNotEquals("private@example.com", stored);
            assertFalse(stored.contains("private@example.com"));
        }
    }

@Test
void databaseConnectionIsClosedAfterRepositoryOperation() throws Exception {
    Database db = testDatabase();

    // Reuse the table created by the existing repository test.
    try (Connection conn = db.connect();
         Statement stmt = conn.createStatement()) {
        stmt.execute("""
            CREATE TABLE IF NOT EXISTS tickets (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                owner_id BIGINT NOT NULL,
                assignee_id BIGINT,
                title VARCHAR(200),
                description VARCHAR(4000),
                contact_enc VARCHAR(2000),
                status VARCHAR(30),
                created_at TIMESTAMP,
                version BIGINT
            )
            """);
    }

    TicketRepository repo = new TicketRepository(db, testEncryptor());

    assertDoesNotThrow(() -> repo.countOpenByOwner(999L));

    // Verify that a subsequent connection can access the database.
    try (Connection conn = db.connect()) {
        assertFalse(conn.isClosed());
    }
}

}
