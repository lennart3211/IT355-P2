package com.ticketapp.db;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

import com.ticketapp.config.AppConfig;

/**
 * Database connection and schema initialization.
 *
 * CWE-798: Database credentials come from AppConfig.
 * CWE-772: JDBC resources use try-with-resources.
 * CWE-455: Initialization failure prevents startup.
 */
public class Database {

    private final AppConfig config;

    public Database(AppConfig config) {
        this.config = config;
    }

    public Connection connect() throws SQLException {
        char[] pw = config.dbPassword();

        try {
            return DriverManager.getConnection(
                    config.dbUrl(),
                    config.dbUser(),
                    new String(pw)
            );
        } finally {
            java.util.Arrays.fill(pw, '\0');
        }
    }

    /**
     * Create required tables during application startup.
     * SQL failures propagate to the caller.
     */
    public void initSchema() throws SQLException {

        try (Connection conn = connect();
             Statement stmt = conn.createStatement()) {

            // User accounts and login throttling
            stmt.executeUpdate("""
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username VARCHAR(100) NOT NULL UNIQUE,
                    password_hash VARBINARY(512) NOT NULL,
                    salt VARBINARY(128) NOT NULL,
                    iterations INT NOT NULL,
                    role_name VARCHAR(50) NOT NULL,
                    email_enc VARCHAR(2048),
                    phone_enc VARCHAR(2048),
                    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
                    failed_logins INT NOT NULL DEFAULT 0,
                    locked_until BIGINT,
                    lockout_count INT NOT NULL DEFAULT 0
                )
                """);

            // Authenticated sessions
            stmt.executeUpdate("""
                CREATE TABLE IF NOT EXISTS sessions (
                    token_hash VARCHAR(64) PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    username VARCHAR(100) NOT NULL,
                    role_name VARCHAR(50) NOT NULL,
                    created_at BIGINT NOT NULL,
                    last_activity BIGINT NOT NULL,
                    CONSTRAINT fk_session_user
                        FOREIGN KEY (user_id)
                        REFERENCES users(id)
                )
                """);

            // Support tickets
            stmt.executeUpdate("""
                CREATE TABLE IF NOT EXISTS tickets (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    owner_id BIGINT NOT NULL,
                    assignee_id BIGINT,
                    title VARCHAR(255) NOT NULL,
                    description VARCHAR(4000),
                    contact_enc VARCHAR(2048),
                    status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
                    created_at TIMESTAMP NOT NULL,
                    version BIGINT NOT NULL DEFAULT 0,
                    CONSTRAINT fk_ticket_owner
                        FOREIGN KEY (owner_id)
                        REFERENCES users(id),
                    CONSTRAINT fk_ticket_assignee
                        FOREIGN KEY (assignee_id)
                        REFERENCES users(id)
                )
                """);

            // Useful indexes for common lookups
            stmt.executeUpdate("""
                CREATE INDEX IF NOT EXISTS idx_ticket_owner
                ON tickets(owner_id)
                """);

            stmt.executeUpdate("""
                CREATE INDEX IF NOT EXISTS idx_ticket_status
                ON tickets(status)
                """);

            stmt.executeUpdate("""
                CREATE INDEX IF NOT EXISTS idx_session_user
                ON sessions(user_id)
                """);
        }
    }
}